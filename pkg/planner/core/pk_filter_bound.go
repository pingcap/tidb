// Hash64 implements the HashEquals interface.
func (s *pkFilterBoundExpr) Hash64(h base2.Hasher) {
	h.HashByte(expression.ScalarSubQFlag)
	h.HashInt64(s.id)
}

// Equals implements the HashEquals interface.
func (s *pkFilterBoundExpr) Equals(other any) bool {
	s2, ok := other.(*pkFilterBoundExpr)
	if !ok {
		return false
	}
	if s == nil || s2 == nil {
		return s == s2
	}
	return s.id == s2.id
}

// Equal implements the Expression interface.
func (s *pkFilterBoundExpr) Equal(_ expression.EvalContext, e expression.Expression) bool {
	return s.Equals(e)
}

// HashCode implements the Expression interface.
func (s *pkFilterBoundExpr) HashCode() []byte {
	if len(s.hashcode) == 0 {
		s.hashcode = append(make([]byte, 0, 9), expression.ScalarSubQFlag)
		s.hashcode = codec.EncodeInt(s.hashcode, s.id)
	}
	return s.hashcode
}

// CanonicalHashCode implements the Expression interface.
func (s *pkFilterBoundExpr) CanonicalHashCode() []byte {
	return s.HashCode()
}

// String implements the Stringer interface.
func (s *pkFilterBoundExpr) String() string {
	if s.isMax {
		return fmt.Sprintf("pk_filter_max(%s)", s.probe.idxName)
	}
	return fmt.Sprintf("pk_filter_min(%s)", s.probe.idxName)
}

