// pkFilterProbe holds the MIN(pk) and MAX(pk) sub-plans generated by the
// GeneratePKFilter rule, and the bounds they produced for one statement
// execution.
//
// The bounds are exposed to the main plan as Constants whose DeferredExpr is a
// pkFilterBoundExpr. When a cached plan is reused, the ranger evaluates those
// constants while rebuilding ranges, which re-runs the probes for the new
// parameter values. A failure at that point makes plan-cache rebuild fail, so
// the statement is simply re-optimized.
//
// A probe is bound to the session that built it, so plans that reference one
// are only kept in the session plan cache, never the instance plan cache.
type pkFilterProbe struct {
	sctx base.PlanContext
	is   infoschema.InfoSchema
	// ctx is the context of the statement execution that evaluates the probe.
	// It is replaced by bindForReuse each time the cached plan is reused.
	ctx              context.Context
	minPlan, maxPlan base.PhysicalPlan
	idxName          string

	// needRebuild is set once the plan is reused from the plan cache, after
	// which the probe plans' ranges must be rebuilt for the new parameters.
	needRebuild bool
	// taskID identifies the statement execution minVal and maxVal belong to.
	taskID         uint64
	evaluated      bool
	minVal, maxVal types.Datum
}

// bindForReuse prepares the probe for a new execution of a cached plan.
func (p *pkFilterProbe) bindForReuse(ctx context.Context) {
	p.ctx = ctx
	p.needRebuild = true
}

// bounds returns MIN(pk) and MAX(pk) for the current statement execution,
// running the probe plans at most once per execution. A NULL bound means no
// row satisfies the probe conditions.
func (p *pkFilterProbe) bounds() (minVal, maxVal types.Datum, err error) {
	taskID := p.sctx.GetSessionVars().StmtCtx.TaskID
	if p.evaluated && p.taskID == taskID {
		return p.minVal, p.maxVal, nil
	}
	if p.needRebuild {
		if err := rebuildRange(p.minPlan); err != nil {
			return minVal, maxVal, err
		}
		if err := rebuildRange(p.maxPlan); err != nil {
			return minVal, maxVal, err
		}
	}
	if minVal, err = p.evalFirstDatum(p.minPlan); err != nil {
		return minVal, maxVal, err
	}
	if maxVal, err = p.evalFirstDatum(p.maxPlan); err != nil {
		return minVal, maxVal, err
	}
	p.minVal, p.maxVal = minVal, maxVal
	p.taskID = taskID
	p.evaluated = true
	return minVal, maxVal, nil
}

func (p *pkFilterProbe) evalFirstDatum(plan base.PhysicalPlan) (types.Datum, error) {
	row, err := EvalSubqueryFirstRow(p.ctx, plan, p.is, p.sctx)
	if err != nil || len(row) == 0 {
		return types.Datum{}, err
	}
	return row[0], nil
}

// pkFilterBoundExpr is the DeferredExpr of a PK filter bound constant. It
// evaluates to the MIN or MAX side of its probe for the current execution.
type pkFilterBoundExpr struct {
	// The embedded Constant only carries RetType; the value always comes
	// from the probe.
	expression.Constant
	probe *pkFilterProbe
	isMax bool
	// id is allocated from the plan column ID space, so it is unique in the
	// statement and does not collide with ScalarSubQueryExpr hash codes.
	id       int64
	hashcode []byte
}

func newPKFilterBoundConstant(sctx base.PlanContext, probe *pkFilterProbe, isMax bool, val types.Datum, retType *types.FieldType) *expression.Constant {
	bound := &pkFilterBoundExpr{
		Constant: expression.Constant{RetType: retType},
		probe:    probe,
		isMax:    isMax,
		id:       sctx.GetSessionVars().AllocPlanColumnID(),
	}
	return &expression.Constant{Value: val, RetType: retType, DeferredExpr: bound}
}

func (s *pkFilterBoundExpr) value() (*expression.Constant, error) {
	minVal, maxVal, err := s.probe.bounds()
	if err != nil {
		return nil, err
	}
	val := minVal
	if s.isMax {
		val = maxVal
	}
	return &expression.Constant{Value: val, RetType: s.RetType}, nil
}

// Eval implements the Expression interface.
func (s *pkFilterBoundExpr) Eval(ctx expression.EvalContext, row chunk.Row) (types.Datum, error) {
	c, err := s.value()
	if err != nil {
		return types.Datum{}, err
	}
	return c.Eval(ctx, row)
}

