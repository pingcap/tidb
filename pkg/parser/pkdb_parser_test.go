package parser_test

import (
	"testing"
)

// TestLogReplication parses administrative statements, restores their SQL and
// rejects malformed syntax, including learner-count integer literals.
func TestLogReplication(t *testing.T) {
	table := []testCase{
		// CREATE/ALTER
		{"ADMIN CREATE LOG REPLICATION test SOURCE_HOST '127.0.0.1'", true, "ADMIN CREATE LOG REPLICATION `test` SOURCE_HOST = '127.0.0.1'"},
		{"ADMIN CREATE LOG REPLICATION test SOURCE_HOST='127.0.0.1' SOURCE_PORT 3306 SOURCE_USER='root' SOURCE_PASSWORD='pwd' PROTECTION_MODE=MAXIMUM_AVAILABILITY DEGRADE_TIMEOUT '30s'", true, "ADMIN CREATE LOG REPLICATION `test` SOURCE_HOST = '127.0.0.1' SOURCE_PORT = 3306 SOURCE_USER = 'root' SOURCE_PASSWORD = 'pwd' PROTECTION_MODE = MAXIMUM_AVAILABILITY DEGRADE_TIMEOUT = '30s'"},
		{"ADMIN CREATE LOG REPLICATION test SOURCE_HOST='127.0.0.1' DETACHED", true, "ADMIN CREATE LOG REPLICATION `test` SOURCE_HOST = '127.0.0.1' DETACHED"},
		{"ADMIN ALTER LOG REPLICATION test SOURCE_HOST='127.0.0.2' SOURCE_PORT=3307 PROTECTION_MODE MAXIMUM_PROTECTION", true, "ADMIN ALTER LOG REPLICATION `test` SOURCE_HOST = '127.0.0.2' SOURCE_PORT = 3307 PROTECTION_MODE = MAXIMUM_PROTECTION"},
		{"ADMIN ALTER LOG REPLICATION test PROTECTION_MODE 0", true, "ADMIN ALTER LOG REPLICATION `test` PROTECTION_MODE = MAXIMUM_PERFORMANCE"},
		{"ADMIN ALTER LOG REPLICATION test PROTECTION_MODE 1 DEGRADE_TIMEOUT '30s'", true, "ADMIN ALTER LOG REPLICATION `test` PROTECTION_MODE = MAXIMUM_AVAILABILITY DEGRADE_TIMEOUT = '30s'"},
		{"ADMIN ALTER LOG REPLICATION test PROTECTION_MODE 2", true, "ADMIN ALTER LOG REPLICATION `test` PROTECTION_MODE = MAXIMUM_PROTECTION"},
		{"ADMIN ALTER LOG REPLICATION test CHANGE SOURCE TO 123", true, "ADMIN ALTER LOG REPLICATION `test` CHANGE SOURCE TO 123"},
		{"ADMIN ALTER LOG REPLICATION test RENAME TO test_renamed", true, "ADMIN ALTER LOG REPLICATION `test` RENAME TO `test_renamed`"},

		// PAUSE/RESUME/DROP
		{"ADMIN CREATE LOG REPLICATION test SOURCE_HOST='127.0.0.1' LEARNER_COUNT=2", true, "ADMIN CREATE LOG REPLICATION `test` SOURCE_HOST = '127.0.0.1' LEARNER_COUNT = 2"},
		{"ADMIN ALTER LOG REPLICATION test LEARNER_COUNT 3", true, "ADMIN ALTER LOG REPLICATION `test` LEARNER_COUNT = 3"},
		{"ADMIN ALTER LOG REPLICATION test PROTECTION_MODE=0 LEARNER_COUNT=4294967295", true, "ADMIN ALTER LOG REPLICATION `test` PROTECTION_MODE = MAXIMUM_PERFORMANCE LEARNER_COUNT = 4294967295"},
		{"ADMIN PAUSE LOG REPLICATION test", true, "ADMIN PAUSE LOG REPLICATION `test`"},
		{"ADMIN RESUME LOG REPLICATION test", true, "ADMIN RESUME LOG REPLICATION `test`"},
		{"ADMIN DROP LOG REPLICATION test", true, "ADMIN DROP LOG REPLICATION `test`"},

		// SWITCHOVER/ACTIVATE STANDBY
		{"ADMIN SWITCHOVER PRIMARY TO 456", true, "ADMIN SWITCHOVER PRIMARY TO 456"},
		{"ADMIN SWITCHOVER AS PRIMARY", true, "ADMIN SWITCHOVER AS PRIMARY"},
		{"ADMIN ACTIVATE STANDBY", true, "ADMIN ACTIVATE STANDBY MODE = DEFAULT"},
		{"ADMIN ACTIVATE STANDBY MODE=DEFAULT", true, "ADMIN ACTIVATE STANDBY MODE = DEFAULT"},
		{"ADMIN ACTIVATE STANDBY MODE=FLASHBACK", true, "ADMIN ACTIVATE STANDBY MODE = FLASHBACK"},
		{"ADMIN ACTIVATE STANDBY MODE = FORCE_COMMIT", true, "ADMIN ACTIVATE STANDBY MODE = FORCE_COMMIT"},
		{"ADMIN ACTIVATE STANDBY FORCE", true, "ADMIN ACTIVATE STANDBY FORCE"},
		{"ADMIN CANCEL LOG REPLICATION WORKFLOW 123", true, "ADMIN CANCEL LOG REPLICATION WORKFLOW 123"},

		// Error cases
		{"ADMIN ALTER LOG REPLICATION test LEARNER_COUNT=-1", false, ""},
		{"ADMIN ALTER LOG REPLICATION test LEARNER_COUNT=1.5", false, ""},
		{"ADMIN ALTER LOG REPLICATION test LEARNER_COUNT=18446744073709551616", false, ""},
		{"ADMIN CREATE LOG REPLICATION test", false, ""},
		{"ADMIN ALTER LOG REPLICATION test SOURCE_HOST = 127", false, ""},
		{"ADMIN ALTER LOG REPLICATION test CHANGE SOURCE TO '123'", false, ""},
		{"ADMIN ALTER LOG REPLICATION test RENAME", false, ""},
		{"ADMIN ALTER LOG REPLICATION test RENAME TO", false, ""},
		{"ADMIN RENAME LOG REPLICATION test TO test_renamed", false, ""},
		{"ADMIN CREATE LOG REPLICATION test SOURCE_HOST='127.0.0.1', SOURCE_PORT=3306", false, ""},
		{"ADMIN CREATE LOG REPLICATION test SOURCE_HOST='127.0.0.1' FOO='bar'", false, ""},
		{"ADMIN PAUSE LOG REPLICATION", false, ""},
		{"ADMIN SWITCHOVER PRIMARY TO abc", false, ""},
		{"ADMIN SWITCHOVER AS PRIMARY 123", false, ""},
		{"ADMIN ACTIVATE STANDBY MODE = UNKNOWN", false, ""},
		{"ADMIN CANCEL LOG REPLICATION WORKFLOW", false, ""},
		{"ADMIN CANCEL LOG REPLICATION FOO 123", false, ""},
		{"ADMIN CANCEL LOG REPLICATION WORKFLOW abc", false, ""},
		{"ADMIN CANCEL LOG REPLICATION WORKFLOW 0abc", false, ""},
	}
	RunTest(t, table, false)
}
