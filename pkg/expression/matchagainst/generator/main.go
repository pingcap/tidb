// Generate TiFlash's Local MATCH character table from the Go standard library.
// Local MATCH requires Unicode 15.0.0; a different toolchain classification
// must fail rather than regenerate a silently changed Unicode 15.0.0 table.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"unicode"
)

func main() {
	output := flag.String("output", "", "TiFlash LocalMatchAgainstTokenChars.h path (required)")
	check := flag.Bool("check", false, "verify the existing header without writing it")
	flag.Parse()
	if *output == "" || flag.NArg() != 0 {
		flag.Usage()
		os.Exit(2)
	}
	if err := writeHeader(*output, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func writeHeader(path string, check bool) error {
	header, err := generateHeader()
	if err != nil {
		return err
	}
	if check {
		existing, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(existing, header) {
			return fmt.Errorf("%s differs from the Unicode 15.0.0 generated table", path)
		}
		return nil
	}
	return os.WriteFile(path, header, 0644)
}

func generateHeader() ([]byte, error) {
	if unicode.Version != "15.0.0" {
		return nil, fmt.Errorf("Local MATCH requires Unicode 15.0.0, got %s; deploy a new TiFlash semantic version before changing TiDB classification", unicode.Version)
	}
	var ranges [][2]rune
	start := rune(-1)
	fingerprint := uint64(14695981039346656037)
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		word := r <= unicode.MaxRune && (unicode.IsLetter(r) || unicode.IsNumber(r) || r == '_')
		if r <= unicode.MaxRune {
			if word {
				fingerprint ^= 1
			}
			fingerprint *= 1099511628211
		}
		if r < 128 {
			continue
		}
		if word && start < 0 {
			start = r
		}
		if !word && start >= 0 {
			ranges = append(ranges, [2]rune{start, r - 1})
			start = -1
		}
	}
	// Do not update this checksum just to make regeneration succeed: the
	// corresponding TiDB tests and TiFlash gtest freeze Unicode 15.0.0 semantics.
	if fingerprint != 0x71f51f3810b3b529 {
		return nil, fmt.Errorf("Unicode 15.0.0 classification changed: fingerprint=%016x", fingerprint)
	}
	var out bytes.Buffer
	out.WriteString(headerPrefix)
	fmt.Fprintf(&out, "inline constexpr std::array<TokenCharRange, %d> token_char_ranges{{\n", len(ranges))
	for _, span := range ranges {
		fmt.Fprintf(&out, "    {0x%X, 0x%X},\n", span[0], span[1])
	}
	out.WriteString(headerSuffix)
	return out.Bytes(), nil
}

