// statsGlobalImpl implements util.StatsGlobal
type statsGlobalImpl struct {
	statsHandler statstypes.StatsHandle
}

// NewStatsGlobal creates a new StatsGlobal.
func NewStatsGlobal(statsHandler statstypes.StatsHandle) statstypes.StatsGlobal {
	return &statsGlobalImpl{statsHandler: statsHandler}
}

// MergePartitionStats2GlobalStatsByTableID merge the partition-level stats to global-level stats based on the tableID.
func (sg *statsGlobalImpl) MergePartitionStats2GlobalStatsByTableID(sc sessionctx.Context,
	opts map[ast.AnalyzeOptionType]uint64, is infoschema.InfoSchema,
	info *statstypes.GlobalStatsInfo,
	physicalID int64,
) (err error) {
	globalStats, err := MergePartitionStats2GlobalStatsByTableID(sc, sg.statsHandler, opts, is, physicalID, info.IsIndex == 1, info.HistIDs)
	if err != nil {
		if types.ErrPartitionStatsMissing.Equal(err) || types.ErrPartitionColumnStatsMissing.Equal(err) {
			// When we find some partition-level stats are missing, we need to report warning.
			sc.GetSessionVars().StmtCtx.AppendWarning(err)
		}
		return err
	}
	return WriteGlobalStatsToStorage(sg.statsHandler, globalStats, info, physicalID)
}

// GlobalStats is used to store the statistics contained in the global-level stats
// which is generated by the merge of partition-level stats.
// It will both store the column stats and index stats.
// In the column statistics, the variable `num` is equal to the number of columns in the partition table.
// In the index statistics, the variable `num` is always equal to one.
type GlobalStats struct {
	Hg                    []*statistics.Histogram
	Cms                   []*statistics.CMSketch
	TopN                  []*statistics.TopN
	MissingPartitionStats []string
	Num                   int
	Count                 int64
	ModifyCount           int64
}

func newGlobalStats(histCount int) *GlobalStats {
	globalStats := new(GlobalStats)
	globalStats.Num = histCount
	globalStats.Count = 0
	globalStats.Hg = make([]*statistics.Histogram, globalStats.Num)
	globalStats.Cms = make([]*statistics.CMSketch, globalStats.Num)
	globalStats.TopN = make([]*statistics.TopN, globalStats.Num)

	return globalStats
}

// MergePartitionStats2GlobalStats merge the partition-level stats to global-level stats based on the tableInfo.
func MergePartitionStats2GlobalStats(
	sc sessionctx.Context,
	statsHandle statstypes.StatsHandle,
	opts map[ast.AnalyzeOptionType]uint64,
	is infoschema.InfoSchema,
	globalTableInfo *model.TableInfo,
	isIndex bool,
	histIDs []int64,
) (*GlobalStats, error) {
	worker := newGlobalStatsMerger(statsHandle, globalTableInfo, histIDs, is)
	err := worker.MergePartitionStats2GlobalStats(sc, opts, isIndex)
	if err != nil {
		return nil, errors.Trace(err)
	}
	return worker.Result(), nil
}

// MergePartitionStats2GlobalStatsByTableID merge the partition-level stats to global-level stats based on the tableID.
func MergePartitionStats2GlobalStatsByTableID(
	sc sessionctx.Context,
	statsHandle statstypes.StatsHandle,
	opts map[ast.AnalyzeOptionType]uint64,
	is infoschema.InfoSchema,
	tableID int64,
	isIndex bool,
	histIDs []int64,
) (globalStats *GlobalStats, err error) {
	// Get the partition table IDs.
	globalTable, ok := statsHandle.TableInfoByID(is, tableID)
	if !ok {
		err = errors.Errorf("unknown physical ID %d in stats meta table, maybe it has been dropped", tableID)
		return
	}

	globalTableInfo := globalTable.Meta()
	globalStats, err = MergePartitionStats2GlobalStats(sc, statsHandle, opts, is, globalTableInfo, isIndex, histIDs)
	if err != nil {
		return nil, errors.Trace(err)
	}
	if len(globalStats.MissingPartitionStats) > 0 {
		var item string
		if !isIndex {
			item = "columns"
		} else {
			item = "index"
			if len(histIDs) > 0 {
				item += " " + globalTableInfo.FindIndexNameByID(histIDs[0])
			}
		}

		logutil.BgLogger().Warn("missing partition stats when merging global stats", zap.String("table", globalTableInfo.Name.L),
			zap.String("item", item), zap.Strings("missing", globalStats.MissingPartitionStats))
	}
	return
}

// uniqueGlobalNDV returns the global NDV of a column or index that
// statistics.UniqueByLocalIndex accepts. Its values never repeat across
// partitions, so the partition NDVs add up exactly, while the merged
// FMSketch estimates the sum.
// A partition that is not analyzed again keeps its NDV after deletes, so the
// current row count bounds the sum, as it bounds the FMSketch estimate.
func uniqueGlobalNDV(partitionHists []*statistics.Histogram, count int64) int64 {
	var ndv int64
	for _, hg := range partitionHists {
		// An empty partition has no histogram.
		if hg != nil {
			ndv += hg.NDV
		}
	}
	return min(ndv, count)
}

// WriteGlobalStatsToStorage is to write global stats to storage
func WriteGlobalStatsToStorage(statsHandle statstypes.StatsHandle, globalStats *GlobalStats, info *statstypes.GlobalStatsInfo, gid int64) (err error) {
	// Dump global-level stats to kv.
	for i := range globalStats.Num {
		hg, cms, topN := globalStats.Hg[i], globalStats.Cms[i], globalStats.TopN[i]
		if hg == nil {
			// All partitions have no stats so global stats are not created.
			continue
		}
		// fms for global stats doesn't need to dump to kv.
		err = statsHandle.SaveColOrIdxStatsToStorage(gid,
			globalStats.Count,
			globalStats.ModifyCount,
			info.IsIndex,
			hg,
			cms,
			topN,
			nil,
			info.StatsVersion,
			true,
		)
		if err != nil {
			statslogutil.StatsLogger().Warn("save global-level stats to storage failed",
				zap.Int64("histID", hg.ID), zap.Error(err), zap.Int64("tableID", gid))
		}
	}
	return err
}

// sampledGlobalNDV limits a sampled NDV, which GEE can scale too high, to the
// current row count and to the non-NULL rows that ANALYZE saw. Those are the
// rows of the merged TopN and histogram, plus missedNotNull for the partitions
// where both are empty.
func sampledGlobalNDV(ndv int64, hist *statistics.Histogram, topN *statistics.TopN, missedNotNull, count int64) int64 {
	notNull := topNHistNotNull(hist, topN) + missedNotNull
	return min(ndv, notNull, count)
}

// topNHistNotNull returns the non-NULL rows that a TopN and histogram hold.
func topNHistNotNull(hist *statistics.Histogram, topN *statistics.TopN) int64 {
	notNull := int64(topN.TotalCount())
	if hist != nil {
		notNull += int64(hist.NotNullCount())
	}
	return notNull
}
