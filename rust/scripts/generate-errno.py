#!/usr/bin/env python3
"""Generate tidb-errno's tables from Go's pkg/errno.

    python3 rust/scripts/generate-errno.py <go-tree> [--check]

<go-tree> is a TiDB Go checkout (the Go master tree the drift ports read,
tidb-wt/gomaster). Writes, from <go-tree>/pkg/errno:
  crates/tidb-errno/src/errcode/codes_generated.rs   (errcode.go's constants,
      in source order, and ALL_CODES)
  crates/tidb-errno/src/errname/catalog_generated.rs (errname.go's
      MySQLErrName messages, in source order, and CATALOG)
Never edit those files by hand; rerun this script. --check writes nothing
and fails when either file differs from what the Go tree generates.
"""

import re
import subprocess
import sys
from pathlib import Path

RUST = Path(__file__).resolve().parents[1]
CODES_OUT = RUST / "crates/tidb-errno/src/errcode/codes_generated.rs"
CATALOG_OUT = RUST / "crates/tidb-errno/src/errname/catalog_generated.rs"

HEADER = (
    "// Copyright 2026 PingCAP, Inc.\n"
    '// Licensed under the Apache License, Version 2.0 (the "License");\n'
    "\n"
    "// Generated by rust/scripts/generate-errno.py from pkg/errno/{file} at Go {rev}.\n"
    "// DO NOT EDIT.\n"
    "\n"
)


def parse_codes(source: str) -> list[tuple[str, int]]:
    """errcode.go's `const ( Name = 1234 ... )`, in source order."""
    block = re.search(r"\nconst \((.*?)\n\)", source, re.S)
    if not block:
        raise SystemExit("errcode.go: no const block")
    codes = []
    for raw in block.group(1).split("\n"):
        line = raw.split("//", 1)[0].strip()
        if not line:
            continue
        m = re.fullmatch(r"(\w+)\s*=\s*(\d+)", line)
        if not m:
            raise SystemExit(f"errcode.go: unexpected line {raw!r}")
        name, value = m.group(1), int(m.group(2))
        if name == "_":
            continue
        codes.append((name, value))
    return codes


def go_unquote(literal: str) -> str:
    """A Go interpreted ("...") or raw (`...`) string literal's value."""
    if literal[0] == "`":
        return literal[1:-1].replace("\r", "")
    body, out, i = literal[1:-1], [], 0
    simple = {"a": "\a", "b": "\b", "f": "\f", "n": "\n", "r": "\r", "t": "\t", "v": "\v",
              "\\": "\\", '"': '"', "'": "'"}
    while i < len(body):
        c = body[i]
        if c != "\\":
            out.append(c)
            i += 1
            continue
        e = body[i + 1]
        if e in simple:
            out.append(simple[e])
            i += 2
        elif e == "x":
            out.append(chr(int(body[i + 2:i + 4], 16)))
            i += 4
        elif e == "u":
            out.append(chr(int(body[i + 2:i + 6], 16)))
            i += 6
        elif e == "U":
            out.append(chr(int(body[i + 2:i + 10], 16)))
            i += 10
        elif e in "01234567":
            out.append(chr(int(body[i + 1:i + 4], 8)))
            i += 4
        else:
            raise SystemExit(f"errname.go: unknown escape \\{e} in {literal}")
    return "".join(out)


def rust_literal(value: str) -> str:
    out = []
    for c in value:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        elif c == "\r":
            out.append("\\r")
        elif ord(c) < 0x20 or ord(c) == 0x7F:
            out.append(f"\\u{{{ord(c):x}}}")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


STRING = r'"(?:[^"\\\n]|\\.)*"|`[^`]*`'


def parse_messages(source: str) -> list[tuple[str, str, list[int]]]:
    """errname.go's `MySQLErrName` entries, in source order."""
    start = re.search(r"var MySQLErrName = map\[uint16\]\*mysql\.ErrMessage\{", source)
    if not start:
        raise SystemExit("errname.go: no MySQLErrName map")
    body = source[start.end():]
    entry = re.compile(
        r"\s*(?://[^\n]*\n\s*)*(\w+):\s*mysql\.Message\(\s*((?:(?:" + STRING + r")\s*\+?\s*)+),\s*"
        r"(nil|\[\]int\{([\d,\s]*)\})\s*,?\s*\),"
    )
    messages, pos = [], 0
    while True:
        rest = body[pos:]
        if re.match(r"\s*(?://[^\n]*\n\s*)*\}", rest):
            return messages
        m = entry.match(rest)
        if not m:
            raise SystemExit(f"errname.go: unexpected entry near {rest[:120]!r}")
        text = "".join(go_unquote(s) for s in re.findall(STRING, m.group(2)))
        positions = [int(p) for p in re.findall(r"\d+", m.group(4) or "")]
        messages.append((m.group(1), text, positions))
        pos += m.end()


def main() -> None:
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    if len(args) != 1:
        raise SystemExit(__doc__)
    go = Path(args[0])
    rev = subprocess.check_output(["git", "-C", str(go), "rev-parse", "--short=11", "HEAD"], text=True).strip()
    codes = parse_codes((go / "pkg/errno/errcode.go").read_text())
    messages = parse_messages((go / "pkg/errno/errname.go").read_text())
    names = {name for name, _ in codes}
    missing = [name for name, _, _ in messages if name not in names]
    if missing:
        raise SystemExit(f"errname.go names without an errcode.go constant: {missing}")

    out = [HEADER.format(file="errcode.go", rev=rev), "#![allow(non_upper_case_globals)]\n\n"]
    for name, value in codes:
        out.append(f"/// `{name}` ({value}).\npub const {name}: u16 = {value};\n")
    out.append("\n/// Every named source constant, including boundary aliases, in source order.\n")
    out.append("pub const ALL_CODES: &[(&str, u16)] = &[\n")
    out.extend(f'    ("{name}", {name}),\n' for name, _ in codes)
    out.append("];\n")
    codes_text = "".join(out)

    out = [HEADER.format(file="errname.go", rev=rev), "#![allow(non_upper_case_globals)]\n\n",
           "use tidb_mysql::errors::{CatalogEntry, ErrMessage};\n\n"]
    for name, text, positions in messages:
        out.append(
            f"/// Message metadata for `{name}`.\n"
            f"pub const {name}: ErrMessage = ErrMessage {{\n"
            f"    raw: {rust_literal(text)},\n"
            f"    redact_arg_pos: &[{', '.join(map(str, positions))}],\n"
            "};\n"
        )
    out.append("\n/// Complete TiDB message catalog in source order.\n")
    out.append("pub const CATALOG: &[CatalogEntry] = &[\n")
    for name, _, _ in messages:
        out.append(
            f"    CatalogEntry {{ name: \"{name}\", code: crate::errcode::{name}, message: {name} }},\n"
        )
    out.append("];\n")
    catalog_text = "".join(out)
    if check:
        stale = [str(path.relative_to(RUST)) for path, text in ((CODES_OUT, codes_text), (CATALOG_OUT, catalog_text))
                 if not path.exists() or path.read_text() != text]
        if stale:
            raise SystemExit(f"stale against Go {rev}: {stale}; rerun without --check")
        print(f"up to date with Go {rev}")
        return
    CODES_OUT.write_text(codes_text)
    CATALOG_OUT.write_text(catalog_text)
    print(f"{len(codes)} codes, {len(messages)} messages from Go {rev}")


if __name__ == "__main__":
    main()
