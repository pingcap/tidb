#!/usr/bin/env python3
"""Generate Rust charset/collation/GB18030 tables from pkg/parser/charset."""

from __future__ import annotations

import ast
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[2]
CHARSET = ROOT / "pkg/parser/charset/charset.go"
GB18030 = ROOT / "pkg/parser/charset/encoding_gb18030_data.go"
GBK = ROOT / "pkg/parser/charset/encoding_gbk.go"
ENCODING_TABLE = ROOT / "pkg/parser/charset/encoding_table.go"
OUTPUT = ROOT / "rust/crates/tidb-datatype/src/charset_data.rs"
ENCODING_OUTPUT = ROOT / "rust/crates/tidb-datatype/src/encoding_labels.rs"


def rust_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rune_literal(value: str) -> str:
    rune = ast.literal_eval(value)
    assert len(rune) == 1
    return f"'\\u{{{ord(rune):x}}}'"


def case_ranges(text: str, marker: str) -> list[tuple[int, ...]]:
    block = text[text.index(marker) :]
    end = block.index("\n\t}")
    pattern = re.compile(
        r"CaseRange\{Lo: 0x([0-9A-Fa-f]+), Hi: 0x([0-9A-Fa-f]+), "
        r"Delta: \[unicode\.MaxCase\]rune\{(-?\d+), (-?\d+), (-?\d+)\}\}"
    )
    return [tuple(int(value, 16 if index < 2 else 10) for index, value in enumerate(match.groups())) for match in pattern.finditer(block[:end])]


def main() -> None:
    charset_text = CHARSET.read_text(encoding="utf-8")
    constants = dict(
        re.findall(r"(?m)^\s*(Charset[A-Za-z0-9]+)\s*=\s*\"([^\"]+)\"", charset_text)
    )
    charset_pattern = re.compile(
        r"(?m)^\s*(Charset[A-Za-z0-9]+):\s*\{Name:\s*(Charset[A-Za-z0-9]+),\s*"
        r"Maxlen:\s*(\d+),\s*DefaultCollation:\s*\"([^\"]+)\",\s*"
        r"Desc:\s*\"([^\"]+)\""
    )
    charsets = [
        (constants[key], int(maxlen), default, description)
        for key, name, maxlen, default, description in charset_pattern.findall(charset_text)
        if key == name
    ]

    collations_block = charset_text.split("var collations = []*Collation{", 1)[1].split("\n}", 1)[0]
    collation_pattern = re.compile(
        r"\{(\d+),\s*\"([^\"]+)\",\s*\"([^\"]+)\",\s*"
        r"(true|false),\s*(\d+),\s*(PadSpace|PadNone)\}"
    )
    collations = [
        (int(identifier), charset, name, default == "true", int(sortlen), pad == "PadSpace")
        for identifier, charset, name, default, sortlen, pad in collation_pattern.findall(collations_block)
    ]

    gb_text = GB18030.read_text(encoding="utf-8")
    mappings = [
        (rune_literal(rune), int(encoded, 16))
        for rune, encoded in re.findall(r"\{('(?:\\.|[^'])+'),\s*(0x[0-9A-Fa-f]+)\}", gb_text)
    ]
    by_rune = sorted(mappings, key=lambda row: int(row[0].split("{")[1][:-2], 16))
    by_bytes = sorted(mappings, key=lambda row: row[1])

    gbk_cases = case_ranges(GBK.read_text(encoding="utf-8"), "var GBKCase")
    gb18030_cases = case_ranges(gb_text, "GB18030Case")

    lines = [
        "// Generated by rust/scripts/generate-parser-charset.py; do not edit.",
        "",
        "pub(crate) const KNOWN_CHARSETS: &[StaticCharsetInfo] = &[",
    ]
    for name, maxlen, default, description in charsets:
        lines.append(
            f"    StaticCharsetInfo {{ name: {rust_string(name)}, default_collation: {rust_string(default)}, description: {rust_string(description)}, maxlen: {maxlen} }},"
        )
    lines.extend(["];", "", "pub(crate) const ALL_COLLATIONS: &[StaticCollationInfo] = &["])
    for identifier, charset, name, default, sortlen, pad_space in collations:
        lines.append(
            f"    StaticCollationInfo {{ id: {identifier}, charset: {rust_string(charset)}, name: {rust_string(name)}, is_default: {str(default).lower()}, sortlen: {sortlen}, pad_space: {str(pad_space).lower()} }},"
        )
    lines.extend(["];", "", "pub(crate) const GB18030_BY_RUNE: &[(char, u32)] = &["])
    lines.extend(f"    ({rune}, 0x{encoded:X})," for rune, encoded in by_rune)
    lines.extend(["];", "", "pub(crate) const GB18030_BY_BYTES: &[(u32, char)] = &["])
    lines.extend(f"    (0x{encoded:X}, {rune})," for rune, encoded in by_bytes)

    def add_cases(name: str, values: list[tuple[int, ...]]) -> None:
        lines.extend(["];", "", f"pub(crate) const {name}: &[CaseRange] = &["])
        lines.extend(
            f"    CaseRange {{ lo: 0x{lo:X}, hi: 0x{hi:X}, upper: {upper}, lower: {lower}, title: {title} }},"
            for lo, hi, upper, lower, title in values
        )

    add_cases("GBK_CASES", gbk_cases)
    add_cases("GB18030_CASES", gb18030_cases)
    lines.append("];")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    encoding_rows = re.findall(
        r'(?m)^\s*"([^"]+)":\s*\{.+,\s*"([^"]+)"\},$',
        ENCODING_TABLE.read_text(encoding="utf-8"),
    )
    assert len(encoding_rows) == 218
    encoding_lines = [
        "// Generated by rust/scripts/generate-parser-charset.py; do not edit.",
        "",
        "const ENCODING_LABELS: &[EncodingLabel] = &[",
    ]
    encoding_lines.extend(
        f"    EncodingLabel {{ label: {rust_string(label)}, canonical: {rust_string(canonical)} }},"
        for label, canonical in encoding_rows
    )
    encoding_lines.append("];")
    ENCODING_OUTPUT.write_text("\n".join(encoding_lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
