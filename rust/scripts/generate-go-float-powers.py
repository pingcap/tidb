#!/usr/bin/env python3
"""Generate the Go 1.27.4 scaling powers used by Rust's fixed-width formatter."""

import re
import subprocess
from pathlib import Path

TOOLCHAIN = "go1.27.4"
OUTPUT = Path(__file__).resolve().parents[1] / "crates/tidb-goruntime/src/go_strconv/powers.rs"


def main() -> None:
    root = subprocess.check_output(
        ["env", f"GOTOOLCHAIN={TOOLCHAIN}", "go", "env", "GOROOT"], text=True
    ).strip()
    source = (Path(root) / "src/internal/strconv/pow10tab.go").read_text()
    rows = re.findall(r"\{(0x[0-9a-f]+), (0x[0-9a-f]+)\}, // 1e(-?\d+) ", source)
    if [int(power) for _, _, power in rows] != list(range(-348, 348)):
        raise SystemExit("Unexpected Go power table")
    literals = "".join(f"    ({hi}, {lo}),\n" for hi, lo, _ in rows)
    OUTPUT.write_text(
        "// Copyright 2025 The Go Authors. All rights reserved.\n"
        "// Use of this source code is governed by a BSD-style license.\n"
        "// See LICENSE-GO in this crate.\n"
        "// Generated by rust/scripts/generate-go-float-powers.py. DO NOT EDIT.\n\n"
        "pub(super) const MIN_POWER: i32 = -348;\n"
        "pub(super) static POW10: [(u64, u64); 696] = [\n"
        f"{literals}];\n"
    )


if __name__ == "__main__":
    main()
