"""Regenerate the Go Unicode category additions used by STR_TO_DATE."""

import os
from pathlib import Path
import subprocess
from tempfile import TemporaryDirectory


GO_VERSION = "go1.27.4"
CATEGORY_VERSION = "1.1.0"
RUST_ROOT = Path(__file__).resolve().parents[1]

GO = """
package main

import (
    "bufio"
    "os"
    "unicode"
)

func main() {
    output := bufio.NewWriter(os.Stdout)
    defer output.Flush()
    for c := rune(0); c <= unicode.MaxRune; c++ {
        var category byte
        switch {
        case unicode.IsLetter(c):
            category = 1
        case unicode.IsNumber(c):
            category = 2
        case unicode.IsPunct(c):
            category = 3
        }
        output.WriteByte(category)
    }
}
"""

RUST = """
use std::io::{BufWriter, Write};
use unicode_general_category::{get_general_category, GeneralCategory::*};

fn main() -> std::io::Result<()> {
    let mut output = BufWriter::new(std::io::stdout());
    for codepoint in 0..=0x10ffff {
        let category = match char::from_u32(codepoint).map(get_general_category) {
            Some(UppercaseLetter | LowercaseLetter | TitlecaseLetter | ModifierLetter | OtherLetter) => 1,
            Some(DecimalNumber | LetterNumber | OtherNumber) => 2,
            Some(ClosePunctuation | ConnectorPunctuation | DashPunctuation | FinalPunctuation
                | InitialPunctuation | OpenPunctuation | OtherPunctuation) => 3,
            _ => 0,
        };
        output.write_all(&[category])?;
    }
    output.flush()
}
"""


def category_tables():
    with TemporaryDirectory() as directory:
        work = Path(directory)
        (work / "main.go").write_text(GO)
        (work / "main.rs").write_text(RUST)
        manifest = work / "Cargo.toml"
        manifest.write_text(f'''[package]
name = "str-to-date-unicode-diff"
version = "0.0.0"
edition = "2021"
[[bin]]
name = "str-to-date-unicode-diff"
path = "main.rs"
[dependencies]
unicode-general-category = "={CATEGORY_VERSION}"
''')
        go = subprocess.check_output(
            ["go", "run", str(work / "main.go")],
            cwd=RUST_ROOT,
            env=dict(os.environ, GOTOOLCHAIN=GO_VERSION),
        )
        rust = subprocess.check_output(
            ["cargo", "run", "--quiet", "--offline", "--release", "--manifest-path", manifest],
            cwd=RUST_ROOT,
        )
    return go, rust


def generate(go, rust):
    assert len(go) == len(rust) == 0x110000
    assert all(previous == current or previous == 0 for current, previous in zip(go, rust))
    yield f'''// Copyright 2026 PingCAP, Inc. Licensed under Apache-2.0.

// @generated by rust/scripts/generate-str-to-date-unicode.py.
// Categories added in Go {GO_VERSION} (Unicode 17.0) relative to
// unicode-general-category {CATEGORY_VERSION} (Unicode 16.0).'''
    for code, category in enumerate(("letters", "numbers", "punctuation"), 1):
        ranges = []
        for character, (current, previous) in enumerate(zip(go, rust)):
            if current != code or current == previous:
                continue
            if ranges and ranges[-1][1] == character - 1:
                ranges[-1][1] = character
            else:
                ranges.append([character, character])
        patterns = []
        for start, end in ranges:
            pattern = f"'\\u{{{start:x}}}'"
            if start != end:
                pattern += f"..='\\u{{{end:x}}}'"
            patterns.append(pattern)
        yield f"\npub(super) fn added_{category}(character: char) -> bool {{"
        yield f"    matches!(character, {' | '.join(patterns)})"
        yield "}"


if __name__ == "__main__":
    target = RUST_ROOT / "crates/tidb-datatype/src/str_to_date/unicode_delta.rs"
    unformatted = "\n".join(generate(*category_tables())) + "\n"
    formatted = subprocess.check_output(["rustfmt"], cwd=RUST_ROOT, input=unformatted, text=True)
    if not target.exists() or target.read_text() != formatted:
        target.write_text(formatted)
