//! Shared Cargo build script for crates with many standalone integration tests.

use std::collections::HashSet;
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("manifest directory"));
    let tests = manifest.join("tests");
    let mut sources: Vec<_> = fs::read_dir(&tests)
        .expect("read tests directory")
        .map(|entry| entry.expect("read test entry").path())
        .filter(|path| {
            path.is_file()
                && path.extension().is_some_and(|extension| extension == "rs")
                && path.file_name().is_some_and(|name| name != "all.rs")
        })
        .collect();
    sources.sort();

    // A test source may be a helper module owned by another integration-test
    // root. Loading it again at the aggregate root duplicates every item,
    // wastes compile time, and trips Clippy's duplicate_mod lint.
    let contents: Vec<_> = sources
        .iter()
        .map(|source| fs::read_to_string(source).expect("read Rust test source"))
        .collect();
    let referenced: HashSet<PathBuf> = sources
        .iter()
        .filter_map(|candidate| {
            let filename = candidate.file_name().and_then(|name| name.to_str())?;
            let path_attribute = format!("#[path = \"{filename}\"]");
            contents
                .iter()
                .any(|source| source.contains(&path_attribute))
                .then(|| candidate.clone())
        })
        .collect();

    let mut modules = String::from("// Generated by scripts/aggregate-tests.rs.\n");
    for (source, source_text) in sources.into_iter().zip(contents) {
        println!("cargo:rerun-if-changed={}", source.display());
        if referenced.contains(&source) || source_text.contains("aggregate-test: standalone") {
            continue;
        }
        let name = source
            .file_stem()
            .and_then(|stem| stem.to_str())
            .expect("UTF-8 Rust test filename");
        assert!(
            name.chars()
                .all(|character| character == '_' || character.is_ascii_alphanumeric()),
            "test filename is not a Rust module name: {}",
            source.display()
        );
        modules.push_str(&format!("#[path = {source:?}]\nmod {name};\n"));
    }
    fs::write(
        PathBuf::from(env::var_os("OUT_DIR").expect("output directory")).join("all_tests.rs"),
        modules,
    )
    .expect("write aggregate test module");
    println!("cargo:rerun-if-changed={}", tests.display());
}
