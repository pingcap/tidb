//! Direct field-name resolution from `pkg/expression/simple_rewriter.go`.

use std::fmt;

use tidb_datatype::{FieldName, QualifiedColumnName};
use tidb_error::mysql::{errcode, FormatArg, SqlError};

/// MySQL `ErrNonUniq`, generated by TiDB's expression error class.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct NonUniqueFieldName {
    /// Shared MySQL catalog rendering, code, and SQLSTATE.
    pub sql_error: SqlError,
}

impl NonUniqueFieldName {
    fn new(column: String) -> Self {
        Self {
            sql_error: SqlError::new(
                errcode::ErrNonUniq,
                &[FormatArg::from(column), FormatArg::from("field list")],
            ),
        }
    }
}

impl fmt::Display for NonUniqueFieldName {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            formatter,
            "[expression:{}]{}",
            self.sql_error.code, self.sql_error.message
        )
    }
}

impl std::error::Error for NonUniqueFieldName {}

/// Finds the source index of a column in a `types.NameSlice`.
///
/// This preserves Go's scan order exactly. Non-explicit fields are ignored;
/// any number of redundant matches retain the first redundant index; a later
/// non-redundant match replaces it; and two non-redundant matches produce
/// `ErrNonUniq` even when redundant matches appeared between them.
pub fn find_field_name(
    names: &[FieldName],
    column: &QualifiedColumnName,
) -> Result<Option<usize>, NonUniqueFieldName> {
    let mut index: Option<usize> = None;

    for (candidate_index, name) in names.iter().enumerate() {
        if name.not_explicit_usable
            || name.names.column.lower != column.column.lower
            || (!column.database.lower.is_empty()
                && column.database.lower != name.names.database.lower)
            || (!column.table.lower.is_empty() && column.table.lower != name.names.table.lower)
        {
            continue;
        }

        if let Some(previous_index) = index {
            if names[previous_index].redundant || name.redundant {
                if !name.redundant {
                    index = Some(candidate_index);
                }
                continue;
            }
            return Err(NonUniqueFieldName::new(column.display_name()));
        }
        index = Some(candidate_index);
    }

    Ok(index)
}

/// Go's `FindFieldNameIdxByColName`: first exact normalized-name match.
pub fn find_field_name_index_by_column(names: &[FieldName], column: &str) -> Option<usize> {
    names
        .iter()
        .position(|name| name.names.column.lower == column)
}

#[cfg(test)]
mod tests {
    use super::*;
    use tidb_datatype::{FieldNameMetadata, IdentifierMetadata};

    fn field_name(db: &str, table: &str, column: &str) -> FieldName {
        FieldName::new(FieldNameMetadata {
            database: IdentifierMetadata::new(db),
            table: IdentifierMetadata::new(table),
            column: IdentifierMetadata::new(column),
            ..Default::default()
        })
    }

    fn qualified_column(db: &str, table: &str, column: &str) -> QualifiedColumnName {
        QualifiedColumnName::new(db, table, column)
    }

    #[test]
    fn find_field_name_matches_simple_rewriter_source_cases() {
        let matching_column = qualified_column("db", "tbl", "col");

        let names = [field_name("db", "tbl", "col")];
        assert_eq!(find_field_name(&names, &matching_column).unwrap(), Some(0));

        let column = qualified_column("", "", "col");
        assert_eq!(find_field_name(&names, &column).unwrap(), Some(0));

        let column = qualified_column("", "tbl", "col");
        assert_eq!(find_field_name(&names, &column).unwrap(), Some(0));

        let column = qualified_column("db", "", "col");
        assert_eq!(find_field_name(&names, &column).unwrap(), Some(0));

        let column = qualified_column("db", "tbl", "col2");
        assert_eq!(find_field_name(&names, &column).unwrap(), None);

        let redundant_first = {
            let mut name = field_name("db", "tbl", "col");
            name.redundant = true;
            name
        };
        let redundant_second = {
            let mut name = field_name("db", "tbl", "col");
            name.redundant = true;
            name
        };
        let non_redundant = field_name("db", "tbl", "col");
        let names = [redundant_first, redundant_second, non_redundant];
        assert_eq!(find_field_name(&names, &matching_column).unwrap(), Some(2));

        let names = [
            field_name("db", "tbl", "col"),
            field_name("db", "tbl", "col"),
        ];
        let err = find_field_name(&names, &matching_column).unwrap_err();
        assert_eq!(err.sql_error.code, errcode::ErrNonUniq);
        assert_eq!(err.sql_error.state, "23000");
        assert_eq!(
            err.sql_error.message,
            "Column 'db.tbl.col' in field list is ambiguous"
        );

        let redundant_first = {
            let mut name = field_name("db", "tbl", "col");
            name.redundant = true;
            name
        };
        let non_redundant = field_name("db", "tbl", "col");
        let names = [redundant_first, non_redundant];
        assert_eq!(find_field_name(&names, &matching_column).unwrap(), Some(1));

        let redundant_first = {
            let mut name = field_name("db", "tbl", "col");
            name.redundant = true;
            name
        };
        let redundant_second = {
            let mut name = field_name("db", "tbl", "col");
            name.redundant = true;
            name
        };
        let redundant_third = {
            let mut name = field_name("db", "tbl", "col");
            name.redundant = true;
            name
        };
        let names = [redundant_first, redundant_second, redundant_third];
        assert_eq!(find_field_name(&names, &matching_column).unwrap(), Some(0));
    }

    #[test]
    fn find_field_name_index_by_column_matches_first_normalized_name() {
        let names = [
            field_name("db", "tbl", "cola"),
            field_name("db", "tbl", "colb"),
            field_name("db", "tbl", "cola"),
        ];
        assert_eq!(find_field_name_index_by_column(&names, "cola"), Some(0));
        assert_eq!(find_field_name_index_by_column(&names, "missing"), None);
    }
}
