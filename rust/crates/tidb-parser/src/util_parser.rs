//! Complete transcreation of `pkg/util/parser` (`ast.go` + `parser.go`).
//!
//! `ast.go` is the SQL-binding restore surface: `GetDefaultDB`,
//! `SimpleCases` with its `findTablePos` scanner, and the two binding
//! restore entry points. `parser.go` is the byte-pattern matcher family
//! (`Match`, `MatchOne`, `AnyPunct`, `AnyChar`, `Char`, `Space`, `Space0`,
//! `Digit`, `Number`) plus a `sync.Pool` of parsers.
//!
//! Two Go surfaces map onto existing Rust shape rather than new code:
//! - `GetParser`/`DestroyParser`/`pool` exist because a goyacc parser is an
//!   expensive reusable object. This crate's parser is a cheap private
//!   per-call object behind the [`crate::parse`] family, so the pool's whole
//!   surface maps to those free functions and nothing is pooled.
//! - Go classifies single BYTES with `unicode.IsPunct/IsSpace/IsDigit` over
//!   `rune(b)`, i.e. the Latin-1 page. The [`is_punct_byte`],
//!   [`is_space_byte`], and [`is_digit_byte`] tables were generated by
//!   executing exactly that Go code over all 256 bytes, not re-derived from
//!   ASCII intuition (`$`, `+`, `<` are NOT punctuation to Go, `\u{85}` and
//!   `\u{A0}` ARE spaces).

use std::error::Error;
use std::fmt;

use tidb_ast::{DmlStmt, InsertStmt, RestoreContext, RestoreFlags, Stmt, Visitable, Visitor};

/// Source `ErrPatternNotMatch`: patterns doesn't match.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub struct PatternNotMatch;

impl fmt::Display for PatternNotMatch {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("Pattern not match")
    }
}

impl Error for PatternNotMatch {}

/// Source `GetDefaultDB`: if any table in the statement lacks an explicit
/// schema name, returns `db_name`; otherwise every table is qualified and
/// the statement needs no default DB, so returns `""`.
#[must_use]
pub fn get_default_db(stmt: &Stmt, db_name: &str) -> String {
    let mut stmt = stmt.clone();
    let mut implicit = ImplicitDatabase {
        has_implicit: false,
    };
    stmt.accept(&mut implicit);
    if implicit.has_implicit {
        db_name.to_owned()
    } else {
        String::new()
    }
}

/// Source `implicitDatabase` visitor. Go checks every `ast.TableName`'s
/// `Schema`; in this AST those are [`tidb_ast::TableRef`] path nodes, plus
/// the INSERT/REPLACE target, which is a plain path on [`InsertStmt`] and
/// not a visited child node.
struct ImplicitDatabase {
    has_implicit: bool,
}

impl Visitor for ImplicitDatabase {
    fn enter(&mut self, node: &mut dyn std::any::Any) -> bool {
        if let Some(table_ref) = node.downcast_ref::<tidb_ast::TableRef>() {
            if table_ref.name.len() == 1 {
                self.has_implicit = true;
            }
            return true;
        }
        if let Some(insert) = node.downcast_ref::<InsertStmt>() {
            if insert.table.len() == 1 {
                self.has_implicit = true;
            }
        }
        // Go: `return in, i.hasImplicit` -- once found, skip the rest.
        self.has_implicit
    }

    fn leave(&mut self, _node: &mut dyn std::any::Any) -> bool {
        true
    }
}

/// Source `findTablePos`: the byte offset of the standalone word `t` in `s`,
/// where words are separated by `' '` or `','`.
fn find_table_pos(s: &str, t: &str) -> Option<usize> {
    let bytes = s.as_bytes();
    let mut l = 0;
    for (i, &b) in bytes.iter().enumerate() {
        if b == b' ' || b == b',' {
            if t.len() == i - l && &bytes[l..i] == t.as_bytes() {
                return Some(l);
            }
            l = i + 1;
        }
    }
    if t.len() == s.len() - l && &bytes[l..] == t.as_bytes() {
        return Some(l);
    }
    None
}

/// Source `SimpleCases`: captures simple `INSERT` statements and qualifies
/// the table by string surgery on the original SQL instead of a full
/// `restore`, keeping the user's own formatting
/// (<https://github.com/pingcap/tidb/issues/22398>).
#[must_use]
pub fn simple_cases(node: &Stmt, default_db: &str, origin: &str) -> Option<String> {
    if origin.is_empty() {
        return None;
    }
    let Stmt::Dml(dml) = node else {
        return None;
    };
    let DmlStmt::Insert(insert) = dml.as_ref() else {
        return None;
    };
    // Go: `insert.Select != nil || insert.Setlist || insert.OnDuplicate !=
    // nil || len(insert.TableHints) != 0` all disqualify, and the target must
    // be one plain table name (`join.Tp == 0 && join.Right == nil` over a
    // `TableSource(TableName)`), which this AST's path form guarantees.
    if insert.source.is_some()
        || insert.set_syntax
        || !insert.on_duplicate.is_empty()
        || !insert.hints.is_empty()
    {
        return None;
    }
    let (schema, table) = match insert.table.as_slice() {
        [table] => ("", table.as_str()),
        [schema, table] => (schema.as_str(), table.as_str()),
        _ => return None,
    };
    let paren_pos = origin.find('(')?;
    if origin[..paren_pos].contains('.') {
        return Some(origin.to_owned());
    }
    let lower = origin[..paren_pos].to_lowercase();
    let pos = find_table_pos(&lower, &table.to_lowercase())?;
    let mut builder = String::with_capacity(origin.len() + schema.len() + default_db.len() + 1);
    builder.push_str(&origin[..pos]);
    if schema.is_empty() {
        builder.push_str(default_db);
    } else {
        builder.push_str(schema);
    }
    builder.push('.');
    builder.push_str(&origin[pos..]);
    Some(builder)
}

/// Source `defaultRestoreFlag`: single-quoted strings, spaces around binary
/// operations, strings without their charset introducer, back-quoted names.
/// This crate's [`RestoreFlags::DEFAULT`] additionally uppercases keywords,
/// which is what Go's restore emits anyway because its `WriteKeyWord` calls
/// pass uppercase text.
#[must_use]
fn default_restore_flags() -> RestoreFlags {
    RestoreFlags::DEFAULT
        | RestoreFlags::SPACES_AROUND_BINARY_OPERATION
        | RestoreFlags::STRING_WITHOUT_CHARSET
}

/// Source `bindingRestoreFlag`: [`default_restore_flags`] plus skipping
/// redundant expression parentheses, only for binding normalization.
#[must_use]
pub fn binding_restore_flags() -> RestoreFlags {
    default_restore_flags() | RestoreFlags::SKIP_REDUNDANT_PARENTHESES
}

/// Source `RestoreWithDefaultDB`: restore strings for a statement with
/// `default_db`, customized for SQL bind usage. `origin` is the statement's
/// original text (Go passes `node.Text()`), which lets [`simple_cases`]
/// answer without a full restore; pass `""` when the text is unavailable and
/// the full restore path is used, exactly as in Go.
#[must_use]
pub fn restore_with_default_db(node: &Stmt, default_db: &str, origin: &str) -> String {
    if let Some(s) = simple_cases(node, default_db, origin) {
        return s;
    }
    node.restore_with_context(
        &RestoreContext::new(binding_restore_flags()).with_default_db(default_db),
    )
}

/// Source `RestoreWithoutDB`: restore strings for a statement with every
/// schema qualifier erased, customized for universal (cross-DB) binding.
#[must_use]
pub fn restore_without_db(node: &Stmt) -> String {
    node.restore_with_context(&RestoreContext::new(
        binding_restore_flags() | RestoreFlags::WITHOUT_SCHEMA_NAME,
    ))
}

/// Go `unicode.IsPunct(rune(b))` for every byte, generated by executing that
/// Go expression over 0..=255.
#[must_use]
pub const fn is_punct_byte(b: u8) -> bool {
    matches!(
        b,
        33 | 34
            | 35
            | 37
            | 38
            | 39
            | 40
            | 41
            | 42
            | 44
            | 45
            | 46
            | 47
            | 58
            | 59
            | 63
            | 64
            | 91
            | 92
            | 93
            | 95
            | 123
            | 125
            | 161
            | 167
            | 171
            | 182
            | 183
            | 187
            | 191
    )
}

/// Go `unicode.IsSpace(rune(b))` for every byte: ASCII whitespace plus
/// U+0085 (NEL) and U+00A0 (NBSP).
#[must_use]
pub const fn is_space_byte(b: u8) -> bool {
    matches!(b, 9..=13 | 32 | 133 | 160)
}

/// Go `unicode.IsDigit(rune(b))` for every byte: exactly `'0'..='9'`.
#[must_use]
pub const fn is_digit_byte(b: u8) -> bool {
    b.is_ascii_digit()
}

/// Source `Match`: matches `pat` at least `times` times and returns the
/// match and the rest, or the whole input with [`PatternNotMatch`].
pub fn match_pat(
    buf: &str,
    pat: impl Fn(u8) -> bool,
    times: usize,
) -> Result<(&str, &str), PatternNotMatch> {
    let bytes = buf.as_bytes();
    let mut i = 0;
    while i < bytes.len() && pat(bytes[i]) {
        i += 1;
    }
    if i < times {
        return Err(PatternNotMatch);
    }
    Ok((&buf[..i], &buf[i..]))
}

/// Source `MatchOne`: matches `pat` exactly once and returns the rest, or
/// the whole input with [`PatternNotMatch`].
pub fn match_one(buf: &str, pat: impl Fn(u8) -> bool) -> Result<&str, PatternNotMatch> {
    let bytes = buf.as_bytes();
    if bytes.is_empty() || !pat(bytes[0]) {
        return Err(PatternNotMatch);
    }
    Ok(&buf[1..])
}

/// Source `AnyPunct`: matches one arbitrary punctuation byte.
pub fn any_punct(buf: &str) -> Result<&str, PatternNotMatch> {
    match_one(buf, is_punct_byte)
}

/// Source `AnyChar`: matches one arbitrary byte.
pub fn any_char(buf: &str) -> Result<&str, PatternNotMatch> {
    match_one(buf, |_| true)
}

/// Source `Char`: matches exactly the byte `c`.
pub fn one_char(buf: &str, c: u8) -> Result<&str, PatternNotMatch> {
    match_one(buf, |x| x == c)
}

/// Source `Space`: matches at least `times` space bytes and returns the
/// rest, or the whole input with [`PatternNotMatch`].
pub fn space(buf: &str, times: usize) -> Result<&str, PatternNotMatch> {
    match_pat(buf, is_space_byte, times).map(|(_, rest)| rest)
}

/// Source `Space0`: skips any leading spaces. Go calls `Space(buf, 0)` and
/// panics on an error that zero-minimum match can never produce; the
/// impossible branch disappears here.
#[must_use]
pub fn space0(buf: &str) -> &str {
    match_pat(buf, is_space_byte, 0)
        .map(|(_, rest)| rest)
        .expect("a zero-minimum match cannot fail")
}

/// Source `Digit`: matches at least `times` digit bytes and returns the
/// digits and the rest.
pub fn digit(buf: &str, times: usize) -> Result<(&str, &str), PatternNotMatch> {
    match_pat(buf, is_digit_byte, times)
}

/// Source `Number`: matches a series of digits and converts it to an int.
/// Like Go's `strconv.Atoi` composition, a digit string that overflows is an
/// error (Go additionally returns the clamped value; the error is the
/// contract).
pub fn number(s: &str) -> Result<(i64, &str), PatternNotMatch> {
    let (digits, rest) = digit(s, 1)?;
    let num = digits.parse::<i64>().map_err(|_| PatternNotMatch)?;
    Ok((num, rest))
}
