/// Returns the explicit SQLSTATE or `HY000`, matching `NewErr`/`NewErrf`.
#[must_use]
pub fn mysql_state(code: u16) -> &'static str {
    MYSQL_STATES
        .iter()
        .find_map(|(entry_code, state)| (*entry_code == code).then_some(*state))
        .unwrap_or(DEFAULT_MYSQL_STATE)
}
