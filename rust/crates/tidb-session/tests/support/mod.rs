//! Shared SQL result rendering for the session integration suites.
//!
//! Go's pkg/testkit owns query/result helpers centrally. These helpers retain
//! the existing Rust suites' distinct rendering and error expectations; they
//! are not a complete transcreation of that package.

use tidb_session::Session;

pub fn integer_rows_with_sql(session: &mut Session, sql: &str) -> String {
    match session.run(sql).unwrap() {
        tidb_session::StmtResult::Rows(rows) => rows
            .into_iter()
            .map(|row| {
                row.iter()
                    .map(|d| match d {
                        tidb_datatype::Datum::Int(i) => format!("{i}"),
                        other => format!("{other:?}"),
                    })
                    .collect::<Vec<_>>()
                    .join("|")
            })
            .collect::<Vec<_>>()
            .join(";"),
        other => panic!("expected rows for {sql}, got {other:?}"),
    }
}

