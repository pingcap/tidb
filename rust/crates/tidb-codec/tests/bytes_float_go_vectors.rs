/// The generator's float cases. `nan` is written as an explicit bit pattern
/// because Go's `math.NaN()` and Rust's `f64::NAN` differ in the low mantissa
/// bit, and the encoding is a pure bit transform.
fn float_cases() -> [(&'static str, f64); 14] {
    [
        ("neg_one", -1.0),
        ("zero", 0.0),
        ("neg_zero", -0.0),
        ("one", 1.0),
        ("max", f64::MAX),
        ("smallest_nonzero", f64::from_bits(1)),
        ("neg_smallest_nonzero", -f64::from_bits(1)),
        ("neg_max", f64::MIN),
        ("inf", f64::INFINITY),
        ("neg_inf", f64::NEG_INFINITY),
        ("nan", f64::from_bits(0x7FF8_0000_0000_0001)),
        ("pi", std::f64::consts::PI),
        ("tiny", 1e-300),
        ("huge", 1e300),
    ]
}

#[test]
fn mem_comparable_floats_match_go() {
    for (name, value) in float_cases() {
        let mut ascending = Vec::new();
        encode_float(&mut ascending, value);
        assert_eq!(ascending, fixture(&format!("float_{name}")), "EncodeFloat({name})");

        let mut descending = Vec::new();
        encode_float_desc(&mut descending, value);
        assert_eq!(
            descending,
            fixture(&format!("float_desc_{name}")),
            "EncodeFloatDesc({name})"
        );

        // Two values do not survive TiDB's own codec, both because the sign
        // bit carries the ordering and cannot also carry itself. Confirmed by
        // running `EncodeFloat`/`DecodeFloat` in Go, not inferred:
        //
        //   -0.0  8000000000000000 -> 8000000000000000 -> 0000000000000000
        //   NaN   7ff8000000000001 -> 8007fffffffffffe -> 0007fffffffffffe
        //
        // `encodeFloatToCmpUint64` takes its non-negative branch for -0.0 and
        // ORs in a bit that is already set; `decodeCmpUintToFloat` clears it,
        // yielding +0.0. NaN takes the negative branch and is complemented,
        // which sets the sign bit, so the decoder clears THAT and returns a
        // subnormal instead of a NaN. Anything relying on a NaN surviving a
        // key encoding is relying on behavior TiDB does not have.
        let expected_back = match name {
            "neg_zero" => 0.0,
            "nan" => f64::from_bits(0x0007_ffff_ffff_fffe),
            _ => value,
        };
        let (remain, decoded) = decode_float(&ascending).unwrap();
        assert!(remain.is_empty());
        assert_eq!(
            decoded.to_bits(),
            expected_back.to_bits(),
            "DecodeFloat({name})"
        );
        let (remain, decoded) = decode_float_desc(&descending).unwrap();
        assert!(remain.is_empty());
        assert_eq!(
            decoded.to_bits(),
            expected_back.to_bits(),
            "DecodeFloatDesc({name})"
        );
    }
}

/// Go's own ordering guarantee, read off the fixture rather than off our
/// encoder: sorting the ascending encodings must sort the values, and the
/// descending encodings must sort them backwards. NaN is excluded because it
/// has no place in a total order over `f64`.
#[test]
fn go_float_bytes_sort_like_the_values() {
    let mut ordered: Vec<(&str, f64)> = float_cases()
        .into_iter()
        .filter(|(name, _)| *name != "nan")
        .collect();
    ordered.sort_by(|left, right| left.1.partial_cmp(&right.1).expect("no NaN remains"));

    let ascending: Vec<Vec<u8>> = ordered
        .iter()
        .map(|(name, _)| fixture(&format!("float_{name}")))
        .collect();
    assert!(
        ascending.windows(2).all(|pair| pair[0] <= pair[1]),
        "Go's ascending float bytes are not value-ordered"
    );

    let descending: Vec<Vec<u8>> = ordered
        .iter()
        .map(|(name, _)| fixture(&format!("float_desc_{name}")))
        .collect();
    assert!(
        descending.windows(2).all(|pair| pair[0] >= pair[1]),
        "Go's descending float bytes are not reverse-value-ordered"
    );
}

fn fixture(name: &str) -> Vec<u8> {
    let prefix = format!("{name}=");
    let hex = FIXTURE
        .lines()
        .find_map(|line| line.strip_prefix(&prefix))
        .unwrap_or_else(|| panic!("fixture has no {name} entry"));
    assert!(hex.len() % 2 == 0, "{name} is not whole bytes");
    hex.as_bytes()
        .chunks_exact(2)
        .map(|pair| (nibble(pair[0]) << 4) | nibble(pair[1]))
        .collect()
}

fn nibble(byte: u8) -> u8 {
    match byte {
        b'0'..=b'9' => byte - b'0',
        b'a'..=b'f' => byte - b'a' + 10,
        _ => panic!("fixture is not lowercase hex"),
    }
}
