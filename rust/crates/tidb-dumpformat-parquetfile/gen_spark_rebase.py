#!/usr/bin/env python3
"""Regenerates src/spark_rebase_micros_generated.rs from Go's
pkg/dumpformat/parquetfile/spark_rebase_micros_generated.go.

Usage: gen_spark_rebase.py <go-file> > src/spark_rebase_micros_generated.rs
"""
import re
import sys

src = open(sys.argv[1]).read()

def array(name):
    m = re.search(r'%s\s*=\s*\[\.\.\.\]int(?:64)?\{(.*?)\n\}' % name, src, re.S)
    if not m:
        m = re.search(r'%s\s*=\s*\[\.\.\.\]int\{(.*?)\}' % name, src, re.S)
    body = re.sub(r'//[^\n]*', '', m.group(1))
    return [int(v) for v in re.findall(r'-?\d+', body)]

date_diffs = array('sparkLegacyDateRebaseDiffs')
date_switch = array('sparkLegacyDateRebaseSwitchDays')
switches = array('sparkJulianGregorianRebaseMicrosSwitches')
diffs = array('sparkJulianGregorianRebaseMicrosDiffs')
records = re.findall(r'\{timeZoneID: "([^"]+)", index: sparkRebaseIndex\{offset: (\d+), length: (\d+)\}\}', src)

def chunks(vals, n=6):
    return '\n'.join('    ' + ', '.join(str(v) for v in vals[i:i + n]) + ',' for i in range(0, len(vals), n))

print('''// Code generated by gen_spark_rebase.py from Go's
// pkg/dumpformat/parquetfile/spark_rebase_micros_generated.go; DO NOT EDIT.
//
// The data comes from Apache Spark v3.5.7's legacy rebase tables
// (julian-gregorian-rebase-micros.json and RebaseDateTime.scala), licensed
// to the Apache Software Foundation under the Apache License, Version 2.0.
// Timestamp switches and diffs are in microseconds, date ones in days.
''')
print('pub(crate) const SPARK_LEGACY_DATE_REBASE_DIFFS: [i64; %d] = [%s];' % (len(date_diffs), ', '.join(map(str, date_diffs))))
print('pub(crate) const SPARK_LEGACY_DATE_REBASE_SWITCH_DAYS: [i64; %d] = [%s];' % (len(date_switch), ', '.join(map(str, date_switch))))
print('\npub(crate) static SWITCHES: [i64; %d] = [\n%s\n];' % (len(switches), chunks(switches)))
print('\npub(crate) static DIFFS: [i64; %d] = [\n%s\n];' % (len(diffs), chunks(diffs)))
print('\n/// `(time zone, offset, length)` into [`SWITCHES`] / [`DIFFS`], sorted by name.')
print('pub(crate) static RECORDS: [(&str, u32, u16); %d] = [' % len(records))
for name, off, ln in sorted(records):
    print('    ("%s", %s, %s),' % (name, off, ln))
print('];')
