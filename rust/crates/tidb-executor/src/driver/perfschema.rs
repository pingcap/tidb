//! Go `pkg/infoschema/perfschema`: the `performance_schema` tables. Go builds
//! each one from its `CREATE TABLE` text (`const.go`) when the package
//! initializes and serves it as a virtual table under the id `tableIDMap`
//! gives it; this builds the same text into every catalog's
//! `performance_schema` database the same way, so `SHOW TABLES`, `DESCRIBE`
//! and `information_schema.tables` answer from the objects themselves.
//!
//! Most tables hold no rows in Go either. The ones Go fills
//! (`session_variables`, `events_statements_summary_by_digest`, ...) get
