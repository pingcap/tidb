/// Go `pkg/executor/aggfuncs/func_percentile_test.go:35::TestPercentile`: six
/// testers `buildAggTester(AggFuncApproxPercentile, tp, 0, 5, nil, <v2>)` over
/// the five generated rows `0..=4` with percent 50. Ordinal rank
/// `k = ceil(50/100 * 5) = 3` (`percentile`, `func_percentile.go:42-46`) is
/// the third-smallest VALUE, `2`, in every domain: `TypeLonglong` -> `2`,
/// `TypeFloat`/`TypeDouble` -> `2.0`, `TypeNewDecimal` -> `2.0`,
/// `TypeDate` -> `TimeFromDays(367)` (rows are days `365..=369`),
/// `TypeDuration` -> 2ns.
///
/// This test drives the real `APPROX_PERCENTILE` build: Go's
/// `buildApproxPercentile` picks the typed accumulator from the ARGUMENT's
/// eval type (`builder.go:172-200`), which is what a SQL argument carries.
/// `TypeFloat` and `TypeDouble` share Go's `percentileOriginal4Real`
/// accumulator, so the real-domain pin here covers both; the Float-code
/// STORAGE cell itself is pinned separately as a gap (see
/// `tests_aggfuncs_mem_merge_slide_gaps::percentile_over_float_storage_cell`).
#[test]
fn approx_percentile_rank_selects_the_third_value_in_every_domain() {
    let catalog = five_row_catalog(
        &[
            ("i", long_type()),
            ("r", double_type()),
            ("d", decimal_type()),
            ("dt", FieldType::new(FieldTypeCode::Date)),
            ("du", FieldType::new(FieldTypeCode::Duration)),
        ],
        |column, row| match column {
            0 => Datum::Int(row as i64),
            1 => Datum::Real(row as f64),
            2 => Datum::Decimal(tidb_datatype::Decimal::from_int(row as i64)),
            3 => date_datum(365 + row as i64),
            _ => duration_datum(row as i64),
        },
    );

    let rows = select(
        "SELECT APPROX_PERCENTILE(i, 50), APPROX_PERCENTILE(r, 50), \
         APPROX_PERCENTILE(d, 50), APPROX_PERCENTILE(dt, 50), \
         APPROX_PERCENTILE(du, 50) FROM t",
        &catalog,
    );
    assert_eq!(rows.len(), 1);
    assert_eq!(rows[0][0], Datum::Int(2));
    assert_eq!(rows[0][1], Datum::Real(2.0));
    assert_eq!(decimal_text(&rows[0][2]), "2");
    assert_eq!(rows[0][3], date_datum(367));
    assert_eq!(rows[0][4], duration_datum(2));
}

/// Go `pkg/executor/aggfuncs/func_percentile_test.go:51::TestFix26807`
/// (pingcap/tidb#26807): for data `1..=28`, `PercentileForTesting(data, 100)`
/// must select the LAST element (`data[index] == 28`) -- percent 100 makes
/// rank `ceil(N) = N`, never an off-by-one. Go loops the selection ten times
/// to shake out randomized pivots in `selection.Select`; this tier's ordinal
/// selection is deterministic, so one pass pins the same contract.
#[test]
fn approx_percentile_at_100_selects_the_maximum_element() {
    let mut catalog = Catalog::default();
    catalog.register(
        "t",
        crate::MemTable {
            columns: vec![("v".to_owned(), long_type())],
            rows: (1..=28).map(|row| vec![Datum::Int(row)]).collect(),
        },
    );

    let rows = select("SELECT APPROX_PERCENTILE(v, 100) FROM t", &catalog);
    assert_eq!(
        rows,
        vec![vec![Datum::Int(28)]],
        "percent 100 over 1..=28 must select 28"
    );
}

/// Go `pkg/executor/aggfuncs/func_percentile_test.go:63::TestFix40463`
/// (pingcap/tidb#40463): an ENUM or SET argument must fall to
/// `basePercentile`, appending NULL for every group -- even when
/// `mysql.EnumSetAsIntFlag` would make the argument look integral. Go forces
/// the eval type to string for `TypeEnum`/`TypeSet`/`TypeBit`
/// (`getEvalTypeForApproxPercentile`, `func_percentile.go:313-329`), and the
/// string domain has no percentile accumulator. The builders here reproduce
/// the same gate (`agg_build.rs`'s `buildApproxPercentile` comment): the enum
/// column's kind strips the `Some(percent)` rank, so every group is NULL.
///
/// The Go tester generates the label values through `getDataGenFunc`'s enum
/// arm (`elems = ["e","d","c","b","a"]`, `value = elems[i+1]`); the VALUES
/// are irrelevant -- the pinned result is the NULL in every group.
#[test]
fn approx_percentile_over_enum_and_set_appends_null_like_go_base_percentile() {
    let mut catalog = Catalog::default();
    let elems = ["e", "d", "c", "b", "a"];
    let rows = (0..5)
        .map(|row| {
            let number = row as u64 + 1;
            vec![
                Datum::new_enum(
                    tidb_datatype::parse_enum_value(&elems, number).expect("enum value"),
                    Collation::Binary,
                ),
                Datum::new_set(
                    tidb_datatype::parse_set_value(&elems, number).expect("set value"),
                    Collation::Binary,
                ),
            ]
        })
        .collect();
    catalog.register(
        "t",
        crate::MemTable {
            columns: vec![
                ("e".to_owned(), FieldType::new(FieldTypeCode::Enum)),
                ("s".to_owned(), FieldType::new(FieldTypeCode::Set)),
            ],
            rows,
        },
    );

    let got = select(
        "SELECT APPROX_PERCENTILE(e, 50), APPROX_PERCENTILE(s, 50) FROM t",
        &catalog,
    );
    assert_eq!(
        got,
        vec![vec![Datum::Null, Datum::Null]],
        "enum/set arguments fall to Go's basePercentile: NULL for every group"
    );
}
