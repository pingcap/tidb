//! Port of Go `pkg/executor/aggfuncs`' single-phase aggregate-behavior tests
//! whose surface this tier owns: the variance family (`func_varpop_test.go`,
//! `func_varsamp_test.go`, `func_stddevpop_test.go`,
//! `func_stddevsamp_test.go`), `SUM` (`func_sum_test.go::TestSum`) and
//! `APPROX_PERCENTILE` (`func_percentile_test.go::TestPercentile`,
//! `TestFix26807`, `TestFix40463`).
//!
//! Go drives `aggfuncs.Build` + `UpdatePartialResult` + `AppendFinalResult2Chunk`
//! directly over rows generated by `aggfunc_test.go:getDataGenFunc` (the values
//! `0..numRows-1`, one per row). This tier folds the same generated values
//! through real SQL (`SELECT VAR_POP(v) ... FROM t` over a registered
//! in-memory table), which lands in the SAME accumulators:
//! `AggKind::Variance`'s incremental fold keeps Go
//! `varPop4Float64.UpdatePartialResult` + `calculateIntermediate`
//! (`pkg/executor/aggfuncs/func_varpop.go:71-99`) operation-for-operation, and
//! `AggKind::Sum`'s decimal/real split keeps Go `buildSum`
//! (`pkg/executor/aggfuncs/builder.go:297-341`). The tests are named after
//! their Go source tests; each sub-case cites the Go tester that pinned it.
//!
//! The white-box halves that have no Rust seam (the per-row memory-delta
//! contracts, the two-partial `MergePartialResult` merges, and the
//! `SlidingWindowAggFunc.Slide` overflow order) are recorded as `#[ignore]`
//! gap tests in the sibling `tests_aggfuncs_mem_merge_slide_gaps` module.

use crate::{run_select_on, Catalog, StmtContext};
use tidb_datatype::{time_from_days, Collation, Datum, FieldType, FieldTypeCode, MySqlDuration};

fn ctx() -> StmtContext {
    StmtContext::for_query()
}

/// A `DATETIME`-free date from Go `types.TimeFromDays`'s day number.
fn date_datum(day_number: i64) -> Datum {
    Datum::Time(time_from_days(day_number))
}

/// Go `getDataGenFunc`'s `mysql.TypeDuration` arm generates
/// `types.Duration{Duration: time.Duration(i)}` -- `i` NANOSECONDS. SQL TIME
/// cells resolve to MICROseconds, so the SQL-surface port generates
/// `i` microseconds at fsp 6 instead (values Go's UT would round to) and
/// pins the same ordinal-rank contract on SQL-representable values.
fn duration_datum(microseconds: i64) -> Datum {
    Datum::Duration(MySqlDuration::from_raw_parts(microseconds * 1_000, 6))
}

/// The five-row source `buildAggTester(funcName, tp, 0, 5, ...)`: one column
/// of generated values `0..=4` per requested type.
///
/// `getDataGenFunc` (`pkg/executor/aggfuncs/aggfunc_test.go:795`) maps each
/// Go type to its generated value; the column name is the caller's choice so
/// one table can carry all the typed columns at once.
fn five_row_catalog(
    columns: &[(&str, FieldType)],
    value_of: impl Fn(usize, usize) -> Datum,
) -> Catalog {
    let mut catalog = Catalog::default();
    let fields: Vec<(String, FieldType)> = columns
        .iter()
        .map(|(name, ft)| {
            let mut ft = ft.clone();
            // A real Go `TIME`/`DATE` column carries its DEFAULT fsp 0
            // (`mysql.DefaultFsp`), which is what keeps the duration
            // coercions in `numeric_context_value` on the fsp-0 path.
            if matches!(
                ft.code(),
                FieldTypeCode::Duration | FieldTypeCode::Date | FieldTypeCode::Datetime
            ) {
                ft.set_decimal(0);
            }
            if ft.code() == FieldTypeCode::Duration {
                ft.set_decimal(6);
            }
            ((*name).to_owned(), ft)
        })
        .collect();
    let rows: Vec<Vec<Datum>> = (0..5)
        .map(|row| {
            (0..columns.len())
                .map(|column| value_of(column, row))
                .collect()
        })
        .collect();
    catalog.register(
        "t",
        crate::MemTable {
            columns: fields,
            rows,
        },
    );
    catalog
}

fn long_type() -> FieldType {
    FieldType::new(FieldTypeCode::LongLong)
}

fn double_type() -> FieldType {
    FieldType::new(FieldTypeCode::Double)
}

fn decimal_type() -> FieldType {
    FieldType::new(FieldTypeCode::NewDecimal)
}

fn select(sql: &str, catalog: &Catalog) -> Vec<Vec<Datum>> {
    run_select_on(sql, catalog, &ctx()).expect("the ported aggregate query must run")
}

/// The exact text of a decimal cell: the Go testers pin the VALUE (10, 2),
/// while this engine stamps its SUM/percentile results with the inferred
/// result shape, so `Datum` equality would compare plan metadata, not the
/// pinned value.
fn decimal_text(value: &Datum) -> String {
    let Datum::Decimal(decimal) = value else {
        panic!("expected a decimal cell, got {value:?}")
    };
    decimal.to_string()
}

/// Go `pkg/executor/aggfuncs/func_varpop_test.go:37::TestVarpop` and
/// `func_varsamp_test.go:33::TestVarsamp` (and their `STDDEV` siblings in
/// `func_stddevpop_test.go:33::TestStddevpop` /
/// `func_stddevsamp_test.go:33::TestStddevsamp`): the four testers share
/// `buildAggTester(fn, mysql.TypeDouble, 0, 5, nil, <value>)`, so all four
/// aggregate the SAME five rows `0.0..=4.0` and compare against one exact
/// `float64` (`testAggFunc`, `aggfunc_test.go:932`).
///
/// Exact expectations, computed by the SAME incremental recurrence Go pins
/// (`calculateIntermediate`, `pkg/executor/aggfuncs/func_varpop.go:66-69`):
/// population variance 10/5 = 2, sample variance 10/4 = 2.5, and the square
/// roots `1.4142135623730951` / `1.5811388300841898` as printed by Go.
#[test]
fn variance_family_over_five_rows_matches_go_exact_floats() {
    let catalog = five_row_catalog(&[("v", double_type())], |_, row| Datum::Real(row as f64));

    let rows = select(
        "SELECT VAR_POP(v), VAR_SAMP(v), STDDEV_POP(v), STDDEV_SAMP(v) FROM t",
        &catalog,
    );
    assert_eq!(rows.len(), 1, "a global aggregate emits exactly one row");
    assert_eq!(
        rows[0],
        vec![
            Datum::Real(2.0),
            Datum::Real(2.5),
            Datum::Real(1.4142135623730951),
            Datum::Real(1.5811388300841898),
        ],
        "variance family must reproduce Go's bit-exact values"
    );
}

/// Go's `testAggFunc` empty-input arm (`aggfunc_test.go:972-982`): after
/// `ResetPartialResult`, `AppendFinalResult2Chunk` over the untouched partial
/// appends `p.results[0]` -- NULL for every member of this family. The SQL
/// equivalent is a global aggregate over an empty table: the stream aggregate
/// still emits its one row, and every variance-family cell is NULL
/// (`VAR_SAMP`/`STDDEV_SAMP` are additionally NULL for a single row, Go's
/// `count-1 <= 0` guard, `func_varpop.go:56-62`).
#[test]
fn variance_family_on_empty_input_appends_null_like_go() {
    let mut catalog = Catalog::default();
    catalog.register(
        "t",
        crate::MemTable {
            columns: vec![("v".to_owned(), double_type())],
            rows: Vec::new(),
        },
    );

    let rows = select(
        "SELECT VAR_POP(v), VAR_SAMP(v), STDDEV_POP(v), STDDEV_SAMP(v) FROM t",
        &catalog,
    );
    assert_eq!(
        rows,
        vec![vec![Datum::Null, Datum::Null, Datum::Null, Datum::Null]],
        "every variance-family aggregate over an empty group is NULL"
    );
}

/// Go `pkg/executor/aggfuncs/func_sum_test.go:50::TestSum`: testers
/// `buildAggTester(AggFuncSum, mysql.TypeNewDecimal, 0, 5, nil, DecFromInt(10))`,
/// `buildAggTester(AggFuncSum, mysql.TypeDouble, 0, 5, nil, 10.0)` and
/// `buildAggTester(AggFuncSumInt, mysql.TypeLonglong, 0, 5, nil, 10)` -- the
/// same five rows `0..=4` per domain, expecting 10, plus NULL on the empty
/// input. At the SQL surface Go's SUM over an integer/decimal argument
/// returns DECIMAL (its RetTp is decimal, folded by `sum4Decimal`,
/// `func_sum.go:203-221`) and over a double argument returns DOUBLE
/// (`baseSum4Float64`, `func_sum.go:76-84`); the engine here keeps the same
/// domain split (`AggKind::Sum`'s decimal-domain integer fold).
///
/// The unsigned white-box half (`buildAggTesterWithFieldType` with the
/// `UnsignedFlag` type, `func_sum_test.go:43-44`) folds through
/// `sumUint` (`func_sum.go:343-366`); at the SQL surface an unsigned column's
/// SUM lands in the same exact decimal domain, so its pinned value is the
/// decimal 10 asserted here as `u`.
#[test]
fn sum_over_decimal_real_and_integer_domains_matches_go() {
    let catalog = five_row_catalog(
        &[
            ("d", decimal_type()),
            ("r", double_type()),
            ("i", long_type()),
            ("u", long_type().with_unsigned(true)),
        ],
        |column, row| match column {
            0 => Datum::Decimal(tidb_datatype::Decimal::from_int(row as i64)),
            1 => Datum::Real(row as f64),
            2 => Datum::Int(row as i64),
            _ => Datum::UInt(row as u64),
        },
    );

    let rows = select("SELECT SUM(d), SUM(r), SUM(i), SUM(u) FROM t", &catalog);
    assert_eq!(rows.len(), 1);
    assert_eq!(rows[0][1], Datum::Real(10.0), "SUM over a double is REAL");
    for (column, label) in [(0, "d"), (2, "i"), (3, "u")] {
        assert_eq!(
            decimal_text(&rows[0][column]),
            "10",
            "SUM over {label} over 0..=4 is the exact decimal 10"
        );
    }
}

